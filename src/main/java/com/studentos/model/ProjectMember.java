package com.studentos.model;

public class ProjectMember {
    private int userId;
    private String role;
    private String displayName;
    private String email;
    public int getUserId() { return userId; } public void setUserId(int userId) { this.userId = userId; }
    public String getRole() { return role; } public void setRole(String role) { this.role = role; }
    public String getDisplayName() { return displayName; } public void setDisplayName(String displayName) { this.displayName = displayName; }
    public String getEmail() { return email; } public void setEmail(String email) { this.email = email; }
}
